import Foundation

/// Uniform type identifiers CopyPal reads, writes or looks for on the pasteboard.
public enum PasteboardTypeID {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let color = "com.apple.cocoa.pasteboard.color"

    // Markers from nspasteboard.org, set by password managers and other tools.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Bundle ID of the app that wrote the pasteboard (optional, rarely set).
    public static let source = "org.nspasteboard.source"

    /// Universal Clipboard: the content was copied on another Apple device.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"

    /// Older, app-specific markers that mean "do not record".
    public static let legacyDoNotRecord: Set<String> = [
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Types CopyPal stores, in order of preference. Everything else is ignored, which
    /// keeps private app formats (and their size) out of the history.
    public static let stored: [String] = [plainText, rtf, html, png, fileURL, url, color]
}

/// One stored pasteboard representation: a type identifier and its bytes. A copy can
/// contain several pasteboard items (e.g. several files); `item` is the item's index.
public struct ClipRepresentation: Sendable, Equatable, Codable {
    public var item: Int
    public var type: String
    public var data: Data

    public init(item: Int = 0, type: String, data: Data) {
        self.item = item
        self.type = type
        self.data = data
    }
}

/// Facts the macOS layer knows about a copy that Core cannot decode itself.
public struct ContentHints: Sendable, Equatable {
    /// Decoded `NSColor` from the pasteboard.
    public var color: ColorValue?

    public init(color: ColorValue? = nil) {
        self.color = color
    }
}

/// Everything read from the pasteboard for one change, before classification.
public struct CapturedContent: Sendable, Equatable {
    public var representations: [ClipRepresentation]
    public var sourceBundleID: String?
    public var origin: ClipOrigin
    public var hints: ContentHints

    public init(
        representations: [ClipRepresentation],
        sourceBundleID: String? = nil,
        origin: ClipOrigin = .local,
        hints: ContentHints = ContentHints()
    ) {
        self.representations = representations
        self.sourceBundleID = sourceBundleID
        self.origin = origin
        self.hints = hints
    }

    public func data(for type: String, item: Int = 0) -> Data? {
        representations.first { $0.item == item && $0.type == type }?.data
    }

    public func contains(_ type: String) -> Bool {
        representations.contains { $0.type == type }
    }

    /// The plain text of the first item, if there is one.
    public var plainText: String? {
        data(for: PasteboardTypeID.plainText).flatMap { String(data: $0, encoding: .utf8) }
    }

    public var byteSize: Int {
        representations.reduce(0) { $0 + $1.data.count }
    }

    /// File URLs of all items, in order.
    public var fileURLs: [URL] {
        representations
            .filter { $0.type == PasteboardTypeID.fileURL }
            .sorted { $0.item < $1.item }
            .compactMap { String(data: $0.data, encoding: .utf8).flatMap(URL.init(string:)) }
    }
}
