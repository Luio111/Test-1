struct PasteboardMarkersTests {
    @Test func concealedIsNeverRead() {
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText, PasteboardTypeID.concealed]) == .skip(.concealed))
    }

    @Test func transientAndLegacyMarkers() {
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText, PasteboardTypeID.transient]) == .skip(.transient))
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText, "com.agilebits.onepassword"]) == .skip(.transient))
    }

    @Test func autoGenerated() {
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText, PasteboardTypeID.autoGenerated]) == .skip(.autoGenerated))
    }

    @Test func remoteAndLocal() {
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText, PasteboardTypeID.remoteClipboard]) == .remote)
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.plainText]) == .read)
        #expect(PasteboardMarkers.decide(types: [PasteboardTypeID.tiff]) == .read)
    }

    @Test func emptyOrUnknown() {
        #expect(PasteboardMarkers.decide(types: []) == .skip(.empty))
        #expect(PasteboardMarkers.decide(types: ["com.example.private"]) == .skip(.unsupported))
    }
}

struct PrivacyFilterTests {
    let now = Date(timeIntervalSince1970: 1_000_000)

    @Test func pauseWins() {
        let settings = PrivacySettings(pausedUntil: now.addingTimeInterval(60))
        #expect(PrivacyFilter.decide(types: [PasteboardTypeID.plainText], sourceBundleID: nil, settings: settings, now: now) == .skip(.paused))
        #expect(PrivacyFilter.decide(types: [PasteboardTypeID.plainText], sourceBundleID: nil, settings: settings, now: now.addingTimeInterval(61)) == .read(origin: .local))
    }

    @Test func ignoredApps() {
        let settings = PrivacySettings()
        #expect(PrivacyFilter.decide(types: [PasteboardTypeID.plainText], sourceBundleID: "com.bitwarden.desktop", settings: settings, now: now) == .skip(.ignoredApp))
        #expect(PrivacyFilter.decide(types: [PasteboardTypeID.plainText], sourceBundleID: "com.apple.TextEdit", settings: settings, now: now) == .read(origin: .local))
    }

    @Test(arguments: [
        (RemoteClipboardMode.ignore, CaptureDecision.skip(.remoteIgnored)),
        (.onDemand, .recordRemotePlaceholder),
        (.readImmediately, .read(origin: .remoteDevice)),
    ])
    func remoteModes(mode: RemoteClipboardMode, expected: CaptureDecision) {
        let settings = PrivacySettings(remoteMode: mode)
        let types = [PasteboardTypeID.plainText, PasteboardTypeID.remoteClipboard]
        #expect(PrivacyFilter.decide(types: types, sourceBundleID: nil, settings: settings, now: now) == expected)
    }

    @Test func markersBeforeRemote() {
        let types = [PasteboardTypeID.plainText, PasteboardTypeID.remoteClipboard, PasteboardTypeID.concealed]
        #expect(PrivacyFilter.decide(types: types, sourceBundleID: nil, settings: PrivacySettings(), now: now) == .skip(.concealed))
    }
}

struct HistoryRulesTests {
    let now = Date(timeIntervalSince1970: 10_000_000)

    private func candidate(_ index: Int, age: TimeInterval, pinned: Bool = false, expires: TimeInterval? = nil, bytes: Int = 10) -> RetentionCandidate {
        RetentionCandidate(
            id: UUID(uuidString: String(format: "00000000-0000-0000-0000-%012d", index))!,
            lastUsedAt: now.addingTimeInterval(-age),
            isPinned: pinned,
            expiresAt: expires.map { now.addingTimeInterval($0) },
            byteSize: bytes
        )
    }

    @Test func keepsWithinLimits() {
        let items = (0..<5).map { candidate($0, age: Double($0)) }
        #expect(HistoryRules.itemsToRemove(items, policy: RetentionPolicy(maxItems: 5), now: now).isEmpty)
    }

    @Test func removesOldestBeyondLimit() {
        let items = (0..<5).map { candidate($0, age: Double($0)) }
        let removed = HistoryRules.itemsToRemove(items, policy: RetentionPolicy(maxItems: 3), now: now)
        #expect(removed == [items[3].id, items[4].id])
    }

    @Test func favoritesNeitherRemovedNorCounted() {
        let items = [candidate(0, age: 0), candidate(1, age: 99_999_999, pinned: true, expires: -10), candidate(2, age: 2)]
        let removed = HistoryRules.itemsToRemove(items, policy: RetentionPolicy(maxItems: 2, maxAge: 100), now: now)
        #expect(removed.isEmpty)
    }

    @Test func expiryAndAge() {
        let items = [candidate(0, age: 0, expires: -1), candidate(1, age: 0, expires: 30), candidate(2, age: 200)]
        let removed = HistoryRules.itemsToRemove(items, policy: RetentionPolicy(maxAge: 100), now: now)
        #expect(removed == [items[0].id, items[2].id])
    }

    @Test func totalSizeRemovesOldestFirst() {
        let items = (0..<4).map { candidate($0, age: Double($0), bytes: 100) }
        let removed = HistoryRules.itemsToRemove(items, policy: RetentionPolicy(maxTotalBytes: 250), now: now)
        #expect(removed == [items[2].id, items[3].id])
    }

    @Test func sizeLimitsPerKind() {
        let policy = RetentionPolicy(maxTextBytes: 100, maxImageBytes: 1_000)
        #expect(HistoryRules.accepts(kind: .text, byteSize: 100, policy: policy))
        #expect(!HistoryRules.accepts(kind: .richText, byteSize: 101, policy: policy))
        #expect(HistoryRules.accepts(kind: .image, byteSize: 1_000, policy: policy))
        #expect(!HistoryRules.accepts(kind: .image, byteSize: 1_001, policy: policy))
        #expect(HistoryRules.accepts(kind: .files, byteSize: .max, policy: policy))
    }

    @Test func sensitiveExpiry() {
        #expect(HistoryRules.expiry(for: .iban, policy: RetentionPolicy(sensitiveLifetime: 60), now: now) == now.addingTimeInterval(60))
        #expect(HistoryRules.expiry(for: nil, policy: .standard, now: now) == nil)
    }
}

struct HistorySearchTests {
    private func item(_ title: String, sensitive: Bool = false, label: String? = nil) -> ClipItem {
        ClipItem(
            createdAt: Date(),
            kind: .text,
            preview: ClipPreview(title: title, searchText: TextFolding.fold(title)),
            sensitivity: sensitive ? .iban : nil,
            pinLabel: label
        )
    }

    @Test func emptyQueryReturnsAll() {
        let items = [item("a"), item("b")]
        #expect(HistorySearch.filter(items, query: "   ") == items)
    }

    @Test func caseAndAccentInsensitive() {
        let items = [item("Rechnung März"), item("Café Paris"), item("Notiz")]
        #expect(HistorySearch.filter(items, query: "rech").map(\.preview.title) == ["Rechnung März"])
        #expect(HistorySearch.filter(items, query: "CAFE").map(\.preview.title) == ["Café Paris"])
        #expect(HistorySearch.filter(items, query: "marz").map(\.preview.title) == ["Rechnung März"])
    }

    @Test func allWordsMustMatch() {
        let items = [item("Rechnung März 2026"), item("Rechnung April")]
        #expect(HistorySearch.filter(items, query: "rechnung märz").map(\.preview.title) == ["Rechnung März 2026"])
    }

    @Test func wordStartsComeFirstThenRecency() {
        let items = [item("Vorrechnung"), item("Rechnung"), item("alte Rechnung")]
        #expect(HistorySearch.filter(items, query: "rech").map(\.preview.title) == ["Rechnung", "alte Rechnung", "Vorrechnung"])
    }

    @Test func sensitiveNeverFound() {
        #expect(HistorySearch.filter([item("DE89 3704", sensitive: true)], query: "de89").isEmpty)
    }

    @Test func favoriteLabelIsSearchable() {
        let items = [item("max@example.com", label: "E-Mail privat")]
        #expect(HistorySearch.filter(items, query: "privat").count == 1)
    }
}
